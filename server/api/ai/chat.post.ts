import { auth } from "../../utils/auth";
import { routePrompt } from "../../utils/ai/router";
import { prompts } from "../../utils/ai/prompts";
import { freeModel } from "~~/server/utils/ai/models";
import type { ChatResponse } from "#shared/types/chat";
import openai from "../../utils/openai";
import { educations, experiences } from "~~/server/db/schema";
import { eq } from "drizzle-orm";

interface Message {
  role: "user" | "assistant";
  content: string;
}

export default defineEventHandler(async (event) => {
  const body = await readBody(event);
  const session = await auth.api.getSession({
    headers: event.headers,
  });

  // Todo: integrate this with the user's plan
  if (!session) {
    return sendError(
      event,
      createError({ statusCode: 401, statusMessage: "Unauthorized" }),
    );
  }

  const messages = body.messages as Message[];

  const userId = session.user.id;
  const [userExperiences, userEducations] = await Promise.all([
    db.select().from(experiences).where(eq(experiences.userId, userId)),

    db.select().from(educations).where(eq(educations.userId, userId)),
  ]);

  messages.push({
    role: "user",
    content: `User Info (autogenerated): ${JSON.stringify({ genericInfo: session.user, experiences: userExperiences, educations: userEducations })}`,
  });

  // Decides which prompt is the best for the occasion
  const route = await routePrompt(messages);

  // Actual response
  const response = await openai.responses.create({
    model: freeModel,
    prompt: prompts[route],
    input: messages,
    store: false,
  });

  try {
    return JSON.parse(response.output_text) as ChatResponse;
  } catch {
    throw createError({
      statusCode: 502,
      statusMessage: "AI returned an invalid response",
    });
  }
});
